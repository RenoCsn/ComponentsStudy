import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const assetsDir = path.join(root, 'src/Components/Icons/assets')
const indexPath = path.join(root, 'src/Components/Icons/index.ts')

const VALID_BASENAME = /^[a-zA-Z][a-zA-Z0-9]*$/

function exportNameFromBasename(basename) {
  return basename[0].toUpperCase() + basename.slice(1) + 'Icon'
}

const entries = fs.readdirSync(assetsDir, { withFileTypes: true })
const basenames = []

for (const ent of entries) {
  if (!ent.isFile() || !ent.name.endsWith('.tsx')) continue
  const basename = ent.name.slice(0, -'.tsx'.length)
  if (!VALID_BASENAME.test(basename)) {
    console.warn(`sync-icon-exports: skipping invalid basename "${ent.name}"`)
    continue
  }
  basenames.push(basename)
}

basenames.sort((a, b) =>
  exportNameFromBasename(a).localeCompare(exportNameFromBasename(b)),
)

const lines = []
for (const basename of basenames) {
  const exportName = exportNameFromBasename(basename)
  const filePath = path.join(assetsDir, `${basename}.tsx`)
  const src = fs.readFileSync(filePath, 'utf8')
  const exportRegex = new RegExp(
    `export\\s+const\\s+${exportName}\\s*[:=]`,
  )
  if (!exportRegex.test(src)) {
    console.error(
      `sync-icon-exports: ${basename}.tsx: expected "export const ${exportName}" — fix filename or export name.`,
    )
    process.exit(1)
  }
  lines.push(`export { ${exportName} } from './assets/${basename}'`)
}

const header = '// Generated by: npm run icons:generate\n'
const content = header + lines.join('\n') + '\n'
fs.writeFileSync(indexPath, content, 'utf8')
console.log(
  `sync-icon-exports: wrote ${lines.length} exports to src/Components/Icons/index.ts`,
)
